/**
 * `forge diagram validate --gate <G-Design|G-Deliver>` and `forge diagram generate --all --check`: the diagram checks
 * the shipped design and delivery gates name (`10` §10.3; `08` §8.11.7's `diagram:*` gate checks), added by
 * `PLAN-M13.md` P26 (Q228).
 *
 * **What is read.** The KB's diagrams: each is a sidecar (`<path>.mmd.yaml`, `08` §8.11.5) beside its source
 * (`<path>.mmd`, the file the sidecar describes; the engine's output check requires both). The rest is project state the
 * §8.11.7 checks need: the component inventory and every artifact id (for `depicts` references), the ADRs (structural
 * coverage), the DataModel documents (persistent state), `paths` and `project.level`/`diagrams.*` from the config. No
 * network, no renderer, no model. The parser is the pure-JS one `08` §8.11.8 names.
 *
 * **`--gate G-Design`** (`10` §10.3's own comment on the check: "syntax, required coverage, ADR diagram coverage, node
 * refs, captions"): every diagram parses (`diagram:syntax`), has its `depicts` resolved (`diagram:refs`), sound labels,
 * a caption and alt text (`requireCaptions`), and stays within the hard complexity limit; at L2 and above the context
 * and container views exist (`architecture/views/context.mmd`, `containers.mmd`, `08` §8.11.3) ; when a DataModel
 * exists (at any level) an ER diagram does; and every structural ADR (category architecture or data, or a blast radius naming more
 * than one component) contains a Mermaid block that parses or lists a registered diagram (`diagram:adr-coverage`). Drift is the
 * separate `diagram:drift` check (`generate --all --check`), not repeated here.
 *
 * **`--gate G-Deliver`** ("deployment topology and pipeline diagrams present and current"): at L2 and above,
 * `delivery/views/pipeline.mmd` and at least one `delivery/views/deployment-<env>.mmd` exist, and each is valid by the
 * checks above and not stale (`review_by` not in the past: `diagram:staleness`, a warning everywhere else in §8.11.7,
 * is an error here because the gate says "current").
 *
 * **`generate --all --check`** (`08` §8.11.6, "for every `generated: true` diagram, a check regenerates it and
 * compares"): regenerates each generated diagram from project state and compares it with its source. Only two of the
 * eight generators have a project-state reader: `components-to-c4` (the component inventory) and `specgraph-to-graph`
 * (the spec graph). A generated diagram from any other generator cannot be regenerated by a command that reads only
 * project state, so it is reported as unverifiable and counts as drifted (a check that cannot show a diagram is in sync
 * has not passed); `forge diagram diff <id> --input <json>` is the manual route, and the honest bypass is
 * `generated: false` or a Waiver. `diagrams.driftPolicy: warn` turns every finding into a warning (the spec's own
 * setting); `autofix` is checked like `fail`, because a gate check never writes.
 *
 * **Not checked here** (recorded in Q228): sequence diagrams per cross-boundary flow, component views (L3+), state
 * diagrams and the other rows of §8.11.3, whose triggers are prose facts no artifact records; `diagram:transclusion`
 * and `diagram:render`; `diagram:refs` for ER diagrams, whose nodes are entity names no registry holds.
 *
 * @see specs/08 §8.11.3, §8.11.6, §8.11.7
 * @see specs/10 §10.3
 * @see PLAN-M13.md P26
 */
